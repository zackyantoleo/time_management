'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'worker/worker.js'), 'utf8');
assert(source.includes('validateWorkPatternReport'), 'Worker v2 no-plan validation missing');
const contract = require('../assets/js/work-pattern-report-contract');
const sample = require('../assets/data/work-patterns.sample.json');
assert.equal(contract.validateWorkPatternReport(sample), sample);
assert.equal(sample.report_kind, 'work_patterns');
assert.equal(sample.schema_version, 2);
assert(sample.report.summary.includes('sintetis'), 'demo must disclose synthetic evidence');
assert(!sample.report.next_week && !sample.report.scorecard && !sample.report.commitments);
const html = fs.readFileSync(path.join(root, 'weekly-wrapped.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'assets/js/weekly-wrapped.js'), 'utf8');
assert(html.includes('id="work-pattern-report"'));
assert(html.includes('id="wrapped-local-input"'), 'private local report opens without an upload');
assert(html.includes('id="wrapped-retry"'));
const context = { console, URLSearchParams, location: { search: '' }, matchMedia: () => ({ matches: true }), WorkPatternReportContract: contract };
vm.createContext(context);
vm.runInContext(js.slice(0, js.lastIndexOf('\nbindWrappedEvents();')), context);
assert.equal(context.validateWrappedData(sample), sample);
assert.throws(() => context.validateWrappedData({ ...sample, report: { ...sample.report, next_week: {} } }), /invalid/);
const legacy = require('../assets/data/weekly-wrapped.sample.json');
context.validateWrappedData(legacy);
console.log('WORK_PATTERN_CATET_CONTRACT_OK: v2, legacy, private open, strict viewer boundary');
